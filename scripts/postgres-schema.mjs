// Generates prisma/postgres/schema.prisma from prisma/schema.prisma (SQLite is the source of truth).
// `--check` exits 1 if the committed Postgres schema is out of date (run in CI).
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("prisma/schema.prisma", "utf8");
const header = "// GENERATED by scripts/postgres-schema.mjs from prisma/schema.prisma. Do not edit by hand.\n";
const generated = header + source.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
const target = "prisma/postgres/schema.prisma";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== generated) {
    console.error(`${target} is out of date. Run: node scripts/postgres-schema.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(target, generated);
  console.log(`Wrote ${target}`);
}
